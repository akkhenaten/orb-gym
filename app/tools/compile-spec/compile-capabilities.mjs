#!/usr/bin/env node
/**
 * Capability compiler.
 *
 * The pack declares 22 capabilities, each with a seven-state contract and the rule that
 * state is "computed from current actual owning records/policy/evidence and permissions
 * at activation/command; no editable is_ready boolean". This compiler projects that
 * contract verbatim. The runtime evaluates it and refuses to accept a stored readiness
 * flag, which is the one thing the specification explicitly forbids.
 */
import { GENERATED_AT } from './build-clock.mjs';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(HERE, '..', '..');
const REPO_ROOT = resolve(APP_ROOT, '..');
const read = (p) => JSON.parse(readFileSync(join(REPO_ROOT, p), 'utf8'));

const pack = read('docs/setup/capability-readiness.json');
const errors = [];

const STATES = ['disabled_optional', 'draft', 'blocked', 'ready', 'enabled', 'suspended', 'needs_revalidation'];

if (pack.capabilities.length !== 22) errors.push(`expected 22 capabilities, found ${pack.capabilities.length}`);

const capabilities = pack.capabilities.map((c) => {
  const states = c.state_contract ?? [];
  if (states.length !== 7) errors.push(`${c.capability_id} declares ${states.length} states, expected 7`);
  for (const s of states) if (!STATES.includes(s)) errors.push(`${c.capability_id} declares unknown state ${s}`);
  if (!c.specification_path) errors.push(`${c.capability_id} cites no specification path`);
  if (!c.evaluation) errors.push(`${c.capability_id} has no evaluation rule`);
  return {
    capability_id: c.capability_id,
    name: c.name,
    states,
    evaluation: c.evaluation,
    conditional_requirements: c.conditional_requirements ?? null,
    safe_independence_rule: c.safe_independence_rule ?? null,
    specification_path: c.specification_path,
    context_sections: c.context_sections ?? [],
  };
});

/**
 * Optional capabilities are disabled by default, and that is a policy fact from the
 * pack, not a guess: trial, junior and community offerings are marked optional, and the
 * extension register records trial availability as disabled until configured.
 */
const OPTIONAL = ['CAP-TRIAL', 'CAP-JUNIOR', 'CAP-COMMUNITY', 'CAP-VENDORS', 'CAP-HR', 'CAP-POS'];
for (const id of OPTIONAL) if (!capabilities.some((c) => c.capability_id === id)) errors.push(`optional capability ${id} is missing`);

const report = {
  generated_at: GENERATED_AT,
  counts: { capabilities: capabilities.length, optional: OPTIONAL.length, states: STATES.length },
  readiness_is_not_permission: pack.readiness_is_not_permission,
  rule: 'State is evaluated from supplied evidence and permissions. A stored is_ready flag is rejected, because the pack forbids one.',
  optional_capabilities: OPTIONAL,
  errors,
};

writeFileSync(join(APP_ROOT, 'generated', 'capabilities.mjs'),
  '// GENERATED by tools/compile-spec/compile-capabilities.mjs. Do not edit by hand.\n'
  + `export const CAPABILITY_STATES = ${JSON.stringify(STATES, null, 1)};\n`
  + `export const CAPABILITIES = ${JSON.stringify(capabilities, null, 1)};\n`
  + `export const OPTIONAL_CAPABILITIES = ${JSON.stringify(OPTIONAL, null, 1)};\n`
  + `export const READINESS_IS_NOT_PERMISSION = ${JSON.stringify(pack.readiness_is_not_permission)};\n`);
writeFileSync(join(APP_ROOT, 'generated', 'capabilities-report.json'), JSON.stringify(report, null, 1));

console.log(JSON.stringify(report.counts, null, 1));
if (errors.length) { console.error(`\nCAPABILITY COMPILE FAILED (${errors.length}):`); errors.slice(0, 10).forEach((e) => console.error('  - ' + e)); process.exit(1); }
console.log('OK  capabilities compiled with their declared state contracts');
