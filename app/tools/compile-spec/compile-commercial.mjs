#!/usr/bin/env node
/**
 * Commercial policy compiler.
 *
 * The contract ships 11 policies with `tenant_values: null` and status
 * SETUP_REQUIRED. That is correct, not a defect: they are tenant-supplied
 * configuration. The defect is that nothing stopped work from proceeding while they
 * were unset, so this compiler registers every policy with its required fields and
 * marks it unconfigured. It never writes a placeholder value: a fabricated
 * cancellation window or approval limit is worse than a refusal.
 */
import { GENERATED_AT } from './build-clock.mjs';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(HERE, '..', '..');
const REPO_ROOT = resolve(APP_ROOT, '..');
const read = (p) => JSON.parse(readFileSync(join(REPO_ROOT, p), 'utf8'));

const doc = read('docs/policy-settings-contract.json');
const errors = [];
const policies = doc.policies ?? [];
if (!policies.length) errors.push('no policies found');

const seen = new Set();
const compiled = policies.map((p) => {
  if (seen.has(p.policy_id)) errors.push(`duplicate policy ${p.policy_id}`);
  seen.add(p.policy_id);
  if (!Array.isArray(p.required_fields) || !p.required_fields.length) {
    errors.push(`${p.policy_id} declares no required fields`);
  }
  if (p.status !== 'SETUP_REQUIRED' && p.tenant_values === null) {
    errors.push(`${p.policy_id} claims ${p.status} but carries no tenant values`);
  }
  // A non-null tenant value in the contract would be a supplied value we cannot verify.
  if (p.tenant_values !== null && p.tenant_values !== undefined) {
    errors.push(`${p.policy_id} ships tenant values; these must come from the tenant, not the spec`);
  }
  return {
    policy_id: p.policy_id,
    scope: p.scope,
    owner: p.owner,
    required_fields: p.required_fields,
    required_when: p.required_when,
    workflows: p.workflows ?? [],
    governing_rule: p.governing_rule,
    status: p.status ?? 'SETUP_REQUIRED',
    configured_in_spec: false,
  };
});

const report = {
  generated_at: GENERATED_AT,
  counts: {
    policies: compiled.length,
    unconfigured: compiled.filter((p) => !p.configured_in_spec).length,
    required_fields_total: compiled.reduce((n, p) => n + p.required_fields.length, 0),
    workflows_referenced: new Set(compiled.flatMap((p) => p.workflows)).size,
    governing_rules: new Set(compiled.map((p) => p.governing_rule)).size,
  },
  enforcement: {
    rule: 'A command that declares a workflow governed by an unconfigured policy is REFUSED with POLICY_UNCONFIGURED. Values are supplied per workspace and cannot come from the specification.',
    limitation: 'The specification has no transition-to-workflow edge, so gating applies only when the caller declares the workflow context.',
  },
  decisions_referenced: [...new Set(compiled.map((p) => p.governing_rule))],
  errors,
};

writeFileSync(join(APP_ROOT, 'generated', 'commercial.mjs'),
  '// GENERATED by tools/compile-spec/compile-commercial.mjs. Do not edit by hand.\n'
  + `export const POLICIES = ${JSON.stringify(compiled, null, 2)};\n`);
writeFileSync(join(APP_ROOT, 'generated', 'commercial-report.json'), JSON.stringify(report, null, 1));

const md = [`# Commercial policy readiness`, '',
  `${compiled.length} policies are declared by the contract and none carries a value.`, '',
  '| Policy | Owner | Required fields | Required when | Status |', '| --- | --- | --- | --- | --- |',
  ...compiled.map((p) => `| \`${p.policy_id}\` | ${p.owner} | ${p.required_fields.length} | ${p.required_when} | ${p.status} |`),
  '', 'Values are supplied per workspace through `POST /api/policies/:policy_id/values` and are never generated.', '',
  `Enforcement: ${report.enforcement.rule}`, '', `Limitation: ${report.enforcement.limitation}`, ''].join('\n');
writeFileSync(join(REPO_ROOT, 'docs', 'derived', 'commercial-readiness.md'), md);

console.log(JSON.stringify(report.counts, null, 1));
if (errors.length) {
  console.error(`\nCOMMERCIAL COMPILE FAILED with ${errors.length} errors:`);
  for (const e of errors) console.error('  - ' + e);
  process.exit(1);
}
console.log('\nOK  commercial registry compiled, no fabricated tenant values');
