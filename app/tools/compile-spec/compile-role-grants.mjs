#!/usr/bin/env node
/**
 * Baseline role grants from docs/access/role-permission-matrix.csv, for actor resolution.
 *
 * Only two cell values are settled authority: ALLOW_OWN_COMPANY (company owner) and
 * ALLOW_IN_AUDITED_PLATFORM_CONTEXT (platform admin). Template cells marked
 * PROPOSED_TEMPLATE_ALLOW_IN_EXPLICIT_SCOPE are editable proposals, "not live grants",
 * and are emitted separately so the runtime can use them only in development. Narrower
 * proposed scopes (self-account, own assigned work, fault reporting...) need a source
 * relationship check this table cannot express, so they are not emitted at all.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(HERE, '..', '..');
const REPO_ROOT = resolve(APP_ROOT, '..');

function parseCsv(text) {
  const rows = []; let row = []; let cell = ''; let q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (ch === '"') q = false; else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') { if (ch === '\r' && text[i + 1] === '\n') i++; row.push(cell); rows.push(row); row = []; cell = ''; }
    else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.length > 1);
}

const [header, ...body] = parseCsv(readFileSync(join(REPO_ROOT, 'docs', 'access', 'role-permission-matrix.csv'), 'utf8'));
const roles = header.slice(1, -1);
const SETTLED = new Set(['ALLOW_OWN_COMPANY', 'ALLOW_IN_AUDITED_PLATFORM_CONTEXT']);
const PROPOSED = 'PROPOSED_TEMPLATE_ALLOW_IN_EXPLICIT_SCOPE';
const out = Object.fromEntries(roles.map((r) => [r, { settled: [], proposed: [] }]));
for (const row of body) {
  const perm = row[0];
  roles.forEach((role, i) => {
    const parts = (row[i + 1] ?? '').split(';');
    if (parts.some((p) => SETTLED.has(p))) out[role].settled.push(perm);
    else if (parts.includes(PROPOSED)) out[role].proposed.push(perm);
  });
}
writeFileSync(join(APP_ROOT, 'generated', 'role-grants.mjs'),
  `// GENERATED by tools/compile-spec/compile-role-grants.mjs. Do not edit by hand.\nexport const ROLE_GRANTS = ${JSON.stringify(out, null, 2)};\n`);
console.log(`OK  ${roles.length} roles; owner ${out['company-owner'].settled.length} settled, platform-admin ${out['platform-admin'].settled.length} settled`);
