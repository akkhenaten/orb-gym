#!/usr/bin/env node
/**
 * Notification contract compiler.
 *
 * Projects docs/notifications/event-catalogue.json into generated/notifications.mjs.
 *
 * IMPORTANT honesty constraint found while compiling: the specification contains
 * NO edge from a transition to a notification event. transition.source_id is a
 * single document reference (OG-DATA-001) for all 233 transitions, and
 * event.source_id is a single reference (OG-NOT-001) for all 91 events, so the
 * two cannot be joined. Commands therefore do NOT auto-fire events. The outbox
 * accepts an explicit event_id from the caller, and this compiler reports the
 * domain-adjacent candidates so the wiring gap is visible rather than guessed.
 */
import { GENERATED_AT } from './build-clock.mjs';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(HERE, '..', '..');
const REPO_ROOT = resolve(APP_ROOT, '..');
const OUT = resolve(APP_ROOT, 'generated');

const read = (p) => JSON.parse(readFileSync(join(REPO_ROOT, p), 'utf8'));
const errors = [];

const catalogue = read('docs/notifications/event-catalogue.json');
const screens = read('docs/design/screen-inventory.json').screens;
const workflows = read('docs/workflows/catalogue.json').workflows;

const events = catalogue.events ?? [];
if (!events.length) errors.push('event catalogue is empty');

const screenIds = new Set(screens.map((s) => s.screen_id));
const workflowIds = new Set(workflows.map((w) => w.workflow_id));
const seen = new Map();

const compiled = events.map((e) => {
  if (seen.has(e.event_id)) errors.push(`duplicate event ${e.event_id}`);
  seen.set(e.event_id, true);

  for (const s of e.candidate_screen_ids ?? []) {
    if (!screenIds.has(s)) errors.push(`${e.event_id}: unknown candidate screen ${s}`);
  }
  for (const w of e.workflow_ids ?? []) {
    if (!workflowIds.has(w)) errors.push(`${e.event_id}: unknown workflow ${w}`);
  }
  if (!e.deduplication_key) errors.push(`${e.event_id}: no deduplication_key`);

  return {
    event_id: e.event_id,
    domain: e.domain,
    name: e.name,
    trigger: e.trigger,
    recipients: e.recipients,
    stop_or_supersede_condition: e.stop_or_supersede_condition,
    action_label: e.action_label,
    delivery_class: e.delivery_class,
    in_app: e.in_app ?? null,
    // The catalogue declares channels as prose, not a list. Coerce honestly: only a
    // real array becomes channels; prose is preserved as a note so nothing is lost
    // and nothing is iterated character-by-character.
    external_channels: Array.isArray(e.external_channels) ? e.external_channels : [],
    external_channels_note: Array.isArray(e.external_channels) ? null : (e.external_channels ?? null),
    deduplication_key: e.deduplication_key,
    privacy: e.privacy ?? null,
    reminder_policy: e.reminder_policy ?? null,
    escalation_policy: e.escalation_policy ?? null,
    delivery_recovery: e.delivery_recovery ?? null,
    read_ack_completion: e.read_ack_completion ?? null,
    workflow_ids: e.workflow_ids ?? [],
    candidate_screen_ids: e.candidate_screen_ids ?? [],
  };
});

const byDomain = new Map();
for (const e of compiled) {
  if (!byDomain.has(e.domain)) byDomain.set(e.domain, []);
  byDomain.get(e.domain).push(e.event_id);
}

// The generator must never claim an edge the source does not contain.
const transitions = read('docs/data/transitions.json').transitions;

const candidatesByDomain = {};
for (const [domain, ids] of byDomain) {
  candidatesByDomain[domain] = {
    events: ids,
    transition_count: transitions.filter((t) => t.workflow_domain === domain).length,
  };
}

const report = {
  generated_at: GENERATED_AT,
  counts: {
    events: compiled.length,
    domains: byDomain.size,
    events_with_candidate_screens: compiled.filter((e) => e.candidate_screen_ids.length).length,
    external_channel_events: compiled.filter((e) => e.external_channels.length).length,
    events_declaring_channels_as_prose: compiled.filter((e) => e.external_channels_note).length,
  },
  mapping: {
    command_to_event_edge_exists: false,
    why: 'transition.source_id is one document reference (OG-DATA-001) and event.source_id is one document reference (OG-NOT-001) for every row, so no join exists.',
    consequence: 'The engine never auto-fires a notification. Callers enqueue an explicit event_id. Domain-adjacent candidates are listed below for wiring review, not used automatically.',
    domain_candidates: candidatesByDomain,
  },
  errors,
};
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'notifications.mjs'),
  '// GENERATED by tools/compile-spec/compile-notify.mjs. Do not edit by hand.\n'
  + `export const EVENTS = ${JSON.stringify(compiled, null, 2)};\n`
  + `export const EVENT_IDS = ${JSON.stringify(compiled.map((e) => e.event_id), null, 2)};\n`);
writeFileSync(join(OUT, 'notification-report.json'), JSON.stringify(report, null, 1));

console.log(JSON.stringify(report.counts, null, 1));
if (errors.length) {
  console.error(`\nNOTIFICATION COMPILE FAILED with ${errors.length} errors:`);
  for (const e of errors.slice(0, 20)) console.error('  - ' + e);
  process.exit(1);
}
console.log('\nOK  notification contract compiled, 0 errors, no invented command edges');
